#include "jy61p.h"
#include <string.h>
/******************************************************************
 * 函 数 名 称：le16
 * 函 数 说 明：将两个小端字节组合为有符号 16 位数值
 * 函 数 形 参：p - 指向至少两个字节的数据地址
 * 函 数 返 回：组合后的原始传感器数值
 ******************************************************************/
static int16_t le16(const uint8_t *p) { return (int16_t)((uint16_t)p[0] | ((uint16_t)p[1] << 8)); }

/******************************************************************
 * 函 数 名 称：jy61p_init
 * 函 数 说 明：清空惯导接收缓冲区、解析状态和有效数据标志
 * 函 数 形 参：s - JY61P 状态地址
 * 函 数 返 回：无
 * 备       注：收到有效角度帧前，超时检查始终视为惯导不可用
 ******************************************************************/
void jy61p_init(JY61P *s) { memset(s, 0, sizeof(*s)); }

/******************************************************************
 * 函 数 名 称：jy61p_feed
 * 函 数 说 明：逐字节接收 11 字节惯导帧，校验并更新航向或角速度
 * 函 数 形 参：s - 解析状态；b - 本次接收字节；now_ms - 当前毫秒数
 * 函 数 返 回：0 未组成完整帧；-1 校验失败；1 完整帧校验通过
 * 备       注：0x52 为角速度帧，0x53 为角度帧；其他类型不更新测量值
 *             只有有效角度帧更新 last_ms 和 valid
 ******************************************************************/
int jy61p_feed(JY61P *s, uint8_t b, uint32_t now_ms) {
    if (s->pos == 0 && b != 0x55) return 0;                 /* 未同步时丢弃非帧头字节 */
    s->buf[s->pos++] = b;                                  /* 按接收顺序装入固定长度帧 */
    if (s->pos < 11) return 0;                             /* 尚未收齐时保留缓冲区 */
    s->pos = 0;                                            /* 完整帧处理后从下一帧头重新接收 */
    uint8_t sum = 0; for (int i = 0; i < 10; ++i) sum += s->buf[i]; /* 前十字节累加并保留低八位 */
    if (sum != s->buf[10]) return -1;                      /* 校验错误不更新测量值和有效时间 */
    if (s->buf[1] == 0x52) s->gyro_z = le16(&s->buf[6]) / 32768.0f * 2000.0f; /* 第 7、8 字节为 Z 轴角速度，小端下标 6、7 */
    if (s->buf[1] == 0x53) { s->yaw = le16(&s->buf[6]) / 32768.0f * 180.0f; s->last_ms = now_ms; s->valid = 1; } /* 第 7、8 字节的航向原始值转换为度并记录时间 */
    return 1;
}
/******************************************************************
 * 函 数 名 称：jy61p_timeout
 * 函 数 说 明：判断是否未收到有效角度帧或角度数据已超时
 * 函 数 形 参：s - 惯导状态；now_ms - 当前毫秒数
 * 函 数 返 回：1 不可用或超时；0 数据仍有效
 * 备       注：超过 300 ms 判超时；无符号时间差兼容毫秒计数折返
 ******************************************************************/
int jy61p_timeout(const JY61P *s, uint32_t now_ms) { return !s->valid || now_ms - s->last_ms > 300; }
